import type { OriginalGraphScene } from './original-graph-scene.ts'
import type { GraphParameterValue } from './original-graph.ts'
import type { Material } from './levels.ts'
import { correctOriginalText } from './original-text-corrections.ts'

export interface OriginalDataArray {
  /** Column name, CKARRAYTYPE (1 int .. 5 parameter) and a parameter column's type GUID. */
  columns: { name: string; type: number; guid?: string }[]
  /** CKDataArray m_ColumnIndex when the array was saved sorted (ascending). */
  sortColumn?: number
  /** `CKDataArray::GetKeyColumn`, -1 when the array has no key column. */
  keyColumn: number
  /** Row-major cells; type-5 cells are the referenced parameter's value. */
  rows: GraphParameterValue[][]
}

export type OriginalDataArraySet = Record<string, Record<string, OriginalDataArray>>

/**
 * Recovered Data Arrays, loaded from the user-supplied original pack. They are
 * generated by `scripts/export-original-arrays.py` into
 * `.local/original/data-arrays.json` and never committed.
 */
export const ORIGINAL_DATA_ARRAYS: OriginalDataArraySet = {}

/** Replace the loaded arrays (used by the local-pack loader and tests). */
export function setOriginalDataArrays(arrays: OriginalDataArraySet): void {
  for (const key of Object.keys(ORIGINAL_DATA_ARRAYS)) delete ORIGINAL_DATA_ARRAYS[key]
  for (const set of Object.values(arrays)) correctOriginalText(set)
  Object.assign(ORIGINAL_DATA_ARRAYS, arrays)
}

let loading: Promise<boolean> | undefined

/** Fetch the generated arrays from the local original pack once. */
export function ensureOriginalDataArrays(url = '/original/data-arrays.json'): Promise<boolean> {
  loading ??= fetch(url).then(async response => {
    if (!response.ok) return false
    setOriginalDataArrays(await response.json() as OriginalDataArraySet)
    return true
  }).catch(() => false)
  return loading
}

/** Find an array by authored name (`CurrentLevel`, `AllLevel`, ...). */
export function originalDataArray(name: string): OriginalDataArray | undefined {
  for (const arrays of Object.values(ORIGINAL_DATA_ARRAYS)) {
    const array = arrays[name]
    if (array) return array
  }
  return undefined
}

/** Authored object name of the live player material (`wood` -> `Ball_Wood`). */
export function originalBallName(material: Material): string {
  return `Ball_${material[0]!.toUpperCase()}${material.slice(1)}`
}

/**
 * The Gameplay `CurrentLevel` array as authored: one row with the level id,
 * ball references (filled by Levelinit at load), reset point, activation phase
 * and points. The level id is the only value the menu rewrites before load;
 * modules read the activation phase from column 4. Returns no rows when the
 * local pack has not been exported, rather than inventing a phase.
 */
export function originalCurrentLevelRows(level: number, ballFrame = 'Ball_Pos_Frame Frame', activeBall?: string): GraphParameterValue[][] {
  const rows = originalDataArray('CurrentLevel')?.rows.map(row => [...row]) ?? []
  if (rows.length === 0) return []
  rows[0]![0] = level
  // Levelinit resolves the authored ball and Ball_Pos_Frame object into these
  // cells; module scripts and the chain's Test read them back.
  if (activeBall !== undefined && rows[0]!.length > 1) rows[0]![1] = activeBall
  if (rows[0]!.length > 2) rows[0]![2] = ballFrame
  return rows
}

/** Register every recovered Data Array on a scene binding. */
export function installOriginalDataArrays(scene: OriginalGraphScene, level?: number): void {
  for (const arrays of Object.values(ORIGINAL_DATA_ARRAYS)) {
    for (const [name, array] of Object.entries(arrays)) scene.setArray(name, array.rows.map(row => [...row]))
  }
  if (level !== undefined) {
    const rows = originalCurrentLevelRows(level)
    if (rows.length > 0) scene.setArray('CurrentLevel', rows)
  }
}
