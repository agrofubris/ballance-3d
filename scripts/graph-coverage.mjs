#!/usr/bin/env node
// Report coverage of the exported Virtools graphs against the behavior registry.
//
// Node 24 imports the TypeScript runtime directly, so the coverage numbers come
// from the same ORIGINAL_BEHAVIORS table the executor uses.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ORIGINAL_BEHAVIORS } from '../src/game/original-graph.ts'
import { TEXT_CONTEXT_BEHAVIORS } from '../src/game/original-graph-text.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const graphDir = join(root, '.local', 'original', 'graphs')
const outputs = [
  join(root, '.local', 'reference', 'graph-coverage.md'),
  join(root, 'docs', 'graph-coverage.md'),
]
const gameplayPrefixes = ['P_Modul_', 'PE_', 'Balls']
// The session runs every document on ORIGINAL_BEHAVIORS (original-session.ts);
// the tutorial wrappers delegate their text blocks to TEXT_CONTEXT_BEHAVIORS.
const known = new Set([...Object.keys(ORIGINAL_BEHAVIORS), ...Object.keys(TEXT_CONTEXT_BEHAVIORS)])

const files = readdirSync(graphDir).filter(name => name.endsWith('.json')).sort((a, b) => a.localeCompare(b))
const graphs = []
const overall = new Map()
const gameplay = new Map()

function add(map, name, graph) {
  const entry = map.get(name) ?? {instances: 0, graphs: new Set()}
  entry.instances += 1
  entry.graphs.add(graph)
  map.set(name, entry)
}

for (const file of files) {
  const data = JSON.parse(readFileSync(join(graphDir, file), 'utf8'))
  // A prototype marks a primitive building block; nodes without one are the
  // document's scripts, which the runtime never dispatches as behaviors.
  const nodes = Object.values(data.nodes)
  const blocks = nodes.filter(node => node.prototype)
  const missing = blocks.filter(node => !known.has(node.name))
  const names = [...new Set(missing.map(node => node.name))].sort((a, b) => a.localeCompare(b))
  const source = data.source.toLowerCase()
  const isGameplay = gameplayPrefixes.some(prefix => source.startsWith(prefix.toLowerCase()))
  for (const node of missing) {
    add(overall, node.name, data.source)
    if (isGameplay) add(gameplay, node.name, data.source)
  }
  graphs.push({
    name: data.source,
    nodes: nodes.length,
    links: data.links.length,
    roots: data.roots,
    missing: names,
  })
}

const byInstances = (a, b) => b[1].instances - a[1].instances || a[0].localeCompare(b[0])
const ranked = [...overall.entries()].sort(byInstances)
const rankedGameplay = [...gameplay.entries()].sort(byInstances)

function graphTable(entries) {
  const lines = [
    '| Graph | Nodes | Links | Roots | Unimplemented names |',
    '| --- | ---: | ---: | --- | ---: |',
  ]
  for (const graph of entries) {
    const roots = graph.roots.length > 0 ? graph.roots.join(', ') : '-'
    lines.push(`| \`${graph.name}\` | ${graph.nodes} | ${graph.links} | ${roots} | ${graph.missing.length} |`)
  }
  return lines
}

function behaviorTable(entries) {
  const lines = [
    '| Behavior | Instances | Graphs |',
    '| --- | ---: | --- |',
  ]
  for (const [name, entry] of entries) {
    lines.push(`| \`${name}\` | ${entry.instances} | ${[...entry.graphs].sort().join(', ')} |`)
  }
  return lines
}

const document = [
  '# Graph coverage',
  '',
  'Generated by `node scripts/graph-coverage.mjs` from the authored graphs exported',
  'into `.local/original/graphs/`. A behavior block (a node with a prototype) is',
  'unimplemented when its name is not a key of `ORIGINAL_BEHAVIORS` (plus the',
  '`TEXT_CONTEXT_BEHAVIORS` names the tutorial wrappers delegate to); script nodes',
  'carry no prototype and are not behaviors. The runtime treats missing blocks as', 'inert.',
  '',
  `Exported graphs: ${graphs.length}. Unimplemented behavior names: ${ranked.length}.`,
  '',
  '## Graphs',
  '',
  ...graphTable(graphs),
  '',
  '## Unimplemented behaviors',
  '',
  ...(ranked.length > 0 ? behaviorTable(ranked) : ['None.']),
  '',
  '## Gameplay-relevant unimplemented behaviors',
  '',
  `Filtered to graphs whose source starts with ${gameplayPrefixes.map(prefix => `\`${prefix}\``).join(', ')}.`,
  '',
  ...(rankedGameplay.length > 0 ? behaviorTable(rankedGameplay) : ['None.']),
  '',
].join('\n')

for (const output of outputs) writeFileSync(output, document)
console.log(`Wrote ${outputs.join(', ')}: ${graphs.length} graphs, ${ranked.length} unimplemented behaviors`)
console.log('Top unimplemented behaviors:')
for (const [name, entry] of ranked.slice(0, 25)) {
  console.log(`  ${entry.instances}\t${name}\t(${[...entry.graphs].sort().join(', ')})`)
}
console.log('Top gameplay-relevant unimplemented behaviors:')
for (const [name, entry] of rankedGameplay.slice(0, 25)) {
  console.log(`  ${entry.instances}\t${name}\t(${[...entry.graphs].sort().join(', ')})`)
}
